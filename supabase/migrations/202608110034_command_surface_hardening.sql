-- Ending a membership is a business command: it validates scope and dates and
-- does not expose arbitrary UPDATE access to the temporal history table.
create or replace function public.end_agent_group_membership(
  target_group_id uuid,
  target_membership_id uuid,
  target_organization_id uuid,
  new_effective_until date
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_membership public.agent_group_memberships;
  target_agent public.agents;
begin
  select membership.*
  into target_membership
  from public.agent_group_memberships membership
  where membership.id = target_membership_id
    and membership.group_id = target_group_id
    and membership.organization_id = target_organization_id
  for update;

  if target_membership.id is null then
    raise exception 'Rattachement introuvable'
      using errcode = 'P2002';
  end if;

  target_agent := public.assert_workforce_agent_access(
    target_membership.agent_id,
    array['platform_admin', 'planning_admin', 'planner', 'hr']::public.app_role[]
  );

  if target_agent.organization_id <> target_organization_id then
    raise exception 'Organisation incohérente pour ce rattachement'
      using errcode = 'P2002';
  end if;

  if new_effective_until is null
    or new_effective_until < target_membership.effective_from then
    raise exception 'La fin du rattachement doit suivre son début'
      using errcode = 'P2001';
  end if;

  update public.agent_group_memberships membership
  set effective_until = case
    when membership.effective_until is null then new_effective_until
    else least(membership.effective_until, new_effective_until)
  end
  where membership.id = target_membership_id
  returning * into target_membership;

  return to_jsonb(target_membership);
end;
$$;

revoke all on function public.end_agent_group_membership(
  uuid, uuid, uuid, date
) from public, anon, authenticated;
grant execute on function public.end_agent_group_membership(
  uuid, uuid, uuid, date
) to authenticated;

