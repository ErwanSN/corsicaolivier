create trigger agent_group_memberships_site_guard
before insert or update of organization_id, group_id, agent_id
on public.agent_group_memberships
for each row execute function public.enforce_agent_group_membership_site();

-- Replanning notifications are produced by the reliable outbox only. The
-- historical trigger used to create a second pending notification directly.
create or replace function public.finalize_published_replanning()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  applied_scenario public.replanning_scenarios;
begin
  if new.status <> 'published' or old.status = 'published' then
    return new;
  end if;

  for applied_scenario in
    update public.replanning_scenarios
    set status = 'applied',
        applied_at = now(),
        updated_at = now()
    where candidate_schedule_version_id = new.id
      and status = 'approved'
    returning *
  loop
    insert into public.outbox_events (
      organization_id,
      site_id,
      topic,
      aggregate_type,
      aggregate_id,
      payload,
      idempotency_key
    ) values (
      applied_scenario.organization_id,
      applied_scenario.site_id,
      'planning.replanning.applied',
      'replanning_scenario',
      applied_scenario.id,
      jsonb_build_object(
        'scenarioId', applied_scenario.id,
        'scenarioIds', jsonb_build_array(applied_scenario.id),
        'scheduleVersionId', new.id,
        'appliedAt', now()
      ),
      'replanning-applied-' || applied_scenario.id::text
    )
    on conflict (organization_id, idempotency_key) do nothing;
  end loop;

  return new;
end;
$$;

revoke all on function public.finalize_published_replanning()
from public, anon, authenticated;

