-- Rejection is coordinated across every weekly scenario generated by one
-- disruption, just like approval/publication. Candidate drafts remain in the
-- immutable history but can no longer become the current working schedule.
create or replace function public.reject_replanning_scenario(
  target_scenario_id uuid,
  rejection_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_scenario public.replanning_scenarios;
  rejected_count integer;
begin
  select scenario.*
  into target_scenario
  from public.replanning_scenarios scenario
  where scenario.id = target_scenario_id
  for update;

  if target_scenario.id is null then
    raise exception 'Replanning scenario not found';
  end if;

  if target_scenario.status not in ('draft', 'simulated', 'approved') then
    raise exception 'Only a pending replanning scenario can be rejected';
  end if;

  if not public.has_role(
    target_scenario.organization_id,
    target_scenario.site_id,
    array['platform_admin', 'planning_admin', 'approver']::public.app_role[]
  ) then
    raise exception 'Insufficient permissions';
  end if;

  if rejection_reason is null
    or char_length(pg_catalog.btrim(rejection_reason)) not between 3 and 500 then
    raise exception 'A valid rejection reason is required';
  end if;

  perform 1
  from public.replanning_scenarios scenario
  where scenario.disruption_event_id = target_scenario.disruption_event_id
    and scenario.status in ('draft', 'simulated', 'approved')
  order by scenario.base_schedule_version_id, scenario.id
  for update;

  update public.schedule_versions candidate
  set superseded_at = coalesce(candidate.superseded_at, clock_timestamp()),
      change_reason = left(
        concat_ws(E'\n', candidate.change_reason, pg_catalog.btrim(rejection_reason)),
        500
      ),
      updated_at = now()
  where candidate.id in (
      select scenario.candidate_schedule_version_id
      from public.replanning_scenarios scenario
      where scenario.disruption_event_id = target_scenario.disruption_event_id
        and scenario.status in ('draft', 'simulated', 'approved')
        and scenario.candidate_schedule_version_id is not null
    )
    and candidate.status in ('draft', 'validated')
    and candidate.superseded_at is null;

  update public.replanning_scenarios scenario
  set status = 'rejected',
      summary = left(
        concat_ws(E'\n', scenario.summary, pg_catalog.btrim(rejection_reason)),
        1000
      ),
      updated_at = now()
  where scenario.disruption_event_id = target_scenario.disruption_event_id
    and scenario.status in ('draft', 'simulated', 'approved');

  get diagnostics rejected_count = row_count;

  return jsonb_build_object(
    'scenarioId', target_scenario.id,
    'disruptionEventId', target_scenario.disruption_event_id,
    'rejectedCount', rejected_count,
    'coordinated', rejected_count > 1
  );
end;
$$;

revoke all on function public.reject_replanning_scenario(uuid, text)
from public, anon, authenticated;
grant execute on function public.reject_replanning_scenario(uuid, text)
to authenticated;

-- Group targets are site-scoped. Prevent a membership from silently applying
-- another site's working rules to an agent.
do $$
begin
  if exists (
    select 1
    from public.agent_group_memberships membership
    join public.agents agent on agent.id = membership.agent_id
    join public.agent_groups agent_group on agent_group.id = membership.group_id
    where membership.organization_id <> agent.organization_id
      or membership.organization_id <> agent_group.organization_id
      or (
        agent_group.site_id is not null
        and agent_group.site_id <> agent.primary_site_id
      )
  ) then
    raise exception 'Existing agent group memberships cross organization or site boundaries'
      using errcode = 'P2002';
  end if;
end;
$$;

create or replace function public.enforce_agent_group_membership_site()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_agent public.agents;
  target_group public.agent_groups;
begin
  select agent.* into target_agent
  from public.agents agent
  where agent.id = new.agent_id;

  select agent_group.* into target_group
  from public.agent_groups agent_group
  where agent_group.id = new.group_id;

  if target_agent.id is null or target_group.id is null
    or new.organization_id <> target_agent.organization_id
    or new.organization_id <> target_group.organization_id
    or (
      target_group.site_id is not null
      and target_group.site_id <> target_agent.primary_site_id
    ) then
    raise exception 'Agent and group must belong to the same organization and site'
      using errcode = 'P2002';
  end if;

  return new;
end;
$$;

revoke all on function public.enforce_agent_group_membership_site()
from public, anon, authenticated;

drop trigger if exists agent_group_memberships_site_guard
